import { describe, expect, it } from 'vitest'
import { parseAmountInput } from '@/lib/utils/amount-input'

describe('parseAmountInput', () => {
  it.each([
    ['0', 0],
    ['12', 12],
    ['12.5', 12.5],
    ['12,5', 12.5],
    ['1234.5', 1234.5],
    ['1234,50', 1234.5],
    ['1 234,50', 1234.5],
    ['1 234,50', 1234.5],
    ['1 234,50', 1234.5],
    ['1,234.50', 1234.5],
    ['1.234,50', 1234.5],
    ['12,345.67', 12345.67],
    ['12.345,67', 12345.67],
    ['1,234,567.89', 1234567.89],
    ['1.234.567,89', 1234567.89],
    ['1,234', 1234],
    ['1.234', 1234],
    ['12,345', 12345],
    ['0,125', 0.125],
    ['0.125', 0.125],
    ['1,2', 1.2],
    ['1,23', 1.23],
    ['1.234.567', 1234567],
    [',5', 0.5],
    ['.5', 0.5],
    ['12.', 12],
    ['12,', 12],
    ['  45 ', 45],
    ['1234567', 1234567],
  ])('parses %j as %s', (input, expected) => {
    expect(parseAmountInput(input)).toBe(expected)
  })

  it.each([
    [''],
    ['   '],
    ['abc'],
    ['12abc'],
    ['-5'],
    ['+5'],
    ['1e3'],
    ['Infinity'],
    ['NaN'],
    ['1,2,3'],
    ['1.2.3'],
    ['12.34.56,7'],
    [','],
    ['.'],
    ['1 2 3 a'],
    ['１２３'],
  ])('rejects %j', (input) => {
    expect(parseAmountInput(input)).toBeNull()
  })
})
